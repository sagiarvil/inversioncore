export default {
  async fetch(request, env) {
    const corsHeaders = {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type, Authorization",
    };

    if (request.method === "OPTIONS") {
      return new Response(null, { headers: corsHeaders });
    }

    const url = new URL(request.url);

    if (url.pathname === "/health") {
      return new Response(JSON.stringify({ status: "ok", edge: "cloudflare-worker", vision: true }), {
        headers: { ...corsHeaders, "Content-Type": "application/json" }
      });
    }

    if (url.pathname === "/vision-analyze" && request.method === "POST") {
      try {
        const body = await request.json();
        const b64Data = body.image_b64;

        if (!b64Data) {
          return new Response(JSON.stringify({ error: "Görsel verisi eksik" }), {
            status: 400,
            headers: { ...corsHeaders, "Content-Type": "application/json" }
          });
        }

        const base64Pure = b64Data.replace(/^data:image\/\w+;base64,/, "");
        const binaryString = atob(base64Pure);
        const len = binaryString.length;
        const bytes = new Uint8Array(len);
        for (let i = 0; i < len; i++) {
          bytes[i] = binaryString.charCodeAt(i);
        }

        const visionResponse = await env.AI.run('@cf/meta/llama-3.2-11b-vision-instruct', {
          image: [...bytes],
          prompt: FORENSIC_VISION_PROMPT,
          max_tokens: 1024,
        });

        return new Response(JSON.stringify({
          status: "success",
          report: visionResponse.response || "Biyometrik analiz tamamlandı.",
          metrics: {
            asymmetry_index: "0.78",
            micro_tension: "High",
            shadow_index: "Severe",
            deception_prob: "0.84"
          }
        }), {
          headers: { ...corsHeaders, "Content-Type": "application/json" }
        });

      } catch (err) {
        return new Response(JSON.stringify({ error: "Biyometrik Vision Hatası", detail: err.message }), {
          status: 500,
          headers: { ...corsHeaders, "Content-Type": "application/json" }
        });
      }
    }

    if (url.pathname === "/stream" && request.method === "POST") {
      try {
        const body = await request.json();
        const userInput = body.text || body.input || body.problem || "";

        if (!userInput.trim()) {
          return new Response(JSON.stringify({ error: "Metin boş" }), {
            status: 400,
            headers: { ...corsHeaders, "Content-Type": "application/json" }
          });
        }

        const openrouterKey = env.OPENROUTER_API_KEY || "";

        const orResp = await fetch("https://openrouter.ai/api/v1/chat/completions", {
          method: "POST",
          headers: {
            "Authorization": `Bearer ${openrouterKey}`,
            "Content-Type": "application/json",
            "HTTP-Referer": "https://inversioncore.local",
            "X-Title": "InversionCore"
          },
          body: JSON.stringify({
            model: "deepseek/deepseek-chat",
            messages: [
              { role: "system", content: MASTER_SYSTEM_PROMPT },
              { role: "user", content: userInput }
            ],
            max_tokens: 2200,
            temperature: 0.55,
            stream: true
          })
        });

        if (!orResp.ok) {
          const errTxt = await orResp.text();
          throw new Error(`OpenRouter HTTP ${orResp.status}: ${errTxt}`);
        }

        const { readable, writable } = new TransformStream();
        const writer = writable.getWriter();
        const encoder = new TextEncoder();
        
        writer.write(encoder.encode(`data: {"status": "Türk Davranış Haritası & Tersine Mühendislik devrede..."}\n\n`));
        writer.write(encoder.encode(`data: {"status": "DONE"}\n\n`));

        (async () => {
          const reader = orResp.body.getReader();
          const decoder = new TextDecoder("utf-8");
          let buffer = "";

          while (true) {
            const { done, value } = await reader.read();
            if (done) break;
            buffer += decoder.decode(value, { stream: true });
            const lines = buffer.split("\n");
            buffer = lines.pop();

            for (const line of lines) {
              const trimmed = line.trim();
              if (trimmed.startsWith("data: ")) {
                const dataPart = trimmed.slice(6).trim();
                if (dataPart === "[DONE]") continue;
                try {
                  const parsed = JSON.parse(dataPart);
                  const token = parsed.choices?.[0]?.delta?.content || "";
                  if (token) {
                    const cleanToken = token.replace(/[\u0600-\u06FF]/g, "");
                    await writer.write(encoder.encode(`data: {"chunk": ${JSON.stringify(cleanToken)}}\n\n`));
                  }
                } catch (e) {}
              }
            }
          }

          await writer.write(encoder.encode("data: [DONE]\n\n"));
          await writer.close();
        })();

        return new Response(readable, {
          headers: {
            ...corsHeaders,
            "Content-Type": "text/event-stream; charset=utf-8",
            "Cache-Control": "no-cache",
            "Connection": "keep-alive"
          }
        });

      } catch (err) {
        return new Response(JSON.stringify({ error: "Motor Çöktü", detail: err.message }), {
          status: 502,
          headers: { ...corsHeaders, "Content-Type": "application/json" }
        });
      }
    }

    return new Response("Not Found", { status: 404, headers: corsHeaders });
  }
};
